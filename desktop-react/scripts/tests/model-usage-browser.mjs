import assert from "node:assert/strict";
const { chromium } = await import(process.env.LOOM_PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ executablePath: process.env.LOOM_CHROMIUM_PATH, headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 760 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem("loom.settings.language", "zh-CN"));
  await page.goto(`${process.env.LOOM_TEST_ORIGIN || "http://127.0.0.1:5173"}/scripts/fixtures/model-usage.html`, { waitUntil: "domcontentloaded", timeout: 60_000 });
  const ring = page.locator(".model-usage-button");
  await page.waitForFunction(() => document.querySelector(".model-usage-value")?.getAttribute("stroke-dasharray") === "61 100");
  const model = await page.locator(".model-chip").boundingBox();
  const circle = await ring.boundingBox();
  assert.ok(circle.x >= model.x + model.width, "ring is right of the model selector");
  await ring.click();
  await page.getByText("61% 剩余", { exact: true }).waitFor();
  await page.getByText("88% 剩余", { exact: true }).waitFor();
  await page.evaluate(() => { window.usageFixture.fail = true; });
  await page.getByRole("button", { name: "刷新", exact: true }).click();
  await page.getByText("查询失败（显示上次结果）", { exact: true }).waitFor();
  await page.getByText("61% 剩余", { exact: true }).waitFor();
  await page.getByRole("button", { name: "deepseek", exact: true }).click();
  await ring.click();
  await page.getByText("CNY 12.3456", { exact: true }).waitFor();
  assert.equal(await page.locator(".model-usage-window").count(), 0);
  await page.evaluate(() => { window.usageFixture.delay = true; });
  await page.getByRole("button", { name: "minimax", exact: true }).click();
  await page.waitForFunction(() => window.usageFixture.pending.length === 1);
  await page.getByRole("button", { name: "unsupported", exact: true }).click();
  await page.evaluate(() => window.usageFixture.pending.shift()());
  await ring.click();
  await page.getByText("此连接暂不支持额度查询", { exact: true }).waitFor();
  assert.equal(await page.locator(".model-usage-window").count(), 0, "late old response cannot replace new selection");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator(".model-usage-popover").count(), 0);
  await page.getByRole("button", { name: "minimax", exact: true }).click();
  await page.setViewportSize({ width: 600, height: 760 });
  await ring.click();
  const popup = await page.locator(".model-usage-popover").boundingBox();
  assert.ok(popup.x >= 0 && popup.x + popup.width <= 600);
  await page.screenshot({ path: process.env.LOOM_USAGE_SCREENSHOT || "C:/WINDOWS/TEMP/loom-model-usage.png" });
  assert.deepEqual(errors, []);
  console.log("Quota UI: position, subscription windows, money, cached failures, switching races, Escape and layout passed.");
} finally { await browser.close(); }
