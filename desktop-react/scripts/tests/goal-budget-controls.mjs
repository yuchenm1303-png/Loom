import assert from "node:assert/strict";
import fs from "node:fs";
const { chromium } = await import(process.env.LOOM_PLAYWRIGHT_MODULE || "playwright-core");
const browser = await chromium.launch({ executablePath: process.env.LOOM_CHROMIUM_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
const out = process.argv[2] || "../.cache/goal-budget";
fs.mkdirSync(out, { recursive: true });
try {
  for (const width of [320, 390, 1280]) {
    const page = await browser.newPage({ viewport: { width, height: 900 } });
    page.setDefaultTimeout(15000);
    const errors = []; page.on("pageerror", error => errors.push(error.message));
    await page.goto("http://127.0.0.1:5199/scripts/fixtures/mobile.html?longgoal=1");
    await page.getByRole("navigation", { name: "主导航" }).getByRole("button", { name: "建造", exact: true }).click();
    await page.getByText("Loom 账号页重做", { exact: true }).click();
    await page.getByRole("navigation", { name: "建造支路" }).getByRole("button", { name: "运行", exact: true }).click();
    await page.getByRole("button", { name: "调整长目标预算", exact: true }).click();
    const editor = page.locator(".goal-budget-control");
    const input = editor.getByRole("spinbutton");
    await input.fill("2000000");
    assert.equal(await editor.getByRole("button", { name: "仅保存预算", exact: true }).isEnabled(), false);
    await input.fill("5500000");
    await editor.getByRole("button", { name: "仅保存预算", exact: true }).click();
    await editor.locator(".goal-budget-balance").filter({ hasText: "总额 5,500,000" }).waitFor();
    const calls = () => page.evaluate(() => window.__shell.calls.filter(c => c.operation === "call" && c.args[0] === "projectWeave/goal").map(c => c.args[1]));
    assert.deepEqual(await calls(), [{ threadId: "thread-build", action: "set_budget", tokenBudget: 5500000, expectedTokenBudget: 4000000, expectedStartedAt: 123 }]);
    assert.equal(await page.getByRole("button", { name: "继续目标", exact: true }).isEnabled(), true, "saving budget keeps the goal paused");
    await editor.getByRole("button", { name: "追加额度", exact: true }).click();
    assert.equal(await input.inputValue(), "");
    await input.fill("1000000");
    await editor.getByRole("button", { name: "保存预算并继续", exact: true }).click();
    await editor.locator(".goal-budget-balance").filter({ hasText: "总额 6,500,000" }).waitFor();
    assert.deepEqual((await calls())[1], { threadId: "thread-build", action: "resume_with_budget", tokenBudget: 6500000, expectedTokenBudget: 5500000, expectedStartedAt: 123 });
    await page.getByRole("button", { name: "暂停目标", exact: true }).waitFor();
    assert.match(await page.locator(".m-build-head .m-badge").innerText(), /运行中/);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `${out}/budget-${width}.png`, animations: "disabled" });
    assert.deepEqual(errors, []);
    await page.close();
  }
  const desktop = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  desktop.setDefaultTimeout(15000);
  await desktop.goto("http://127.0.0.1:5199/scripts/fixtures/project-flow.html?at=0&longgoal=1");
  await desktop.getByRole("button", { name: "调整长目标预算", exact: true }).click();
  await desktop.locator(".goal-budget-editor input").fill("4800000");
  await desktop.getByRole("button", { name: "保存预算并继续", exact: true }).click();
  await desktop.waitForFunction(() => window.goalBudgetCall?.tokenBudget === 4800000);
  assert.deepEqual(await desktop.evaluate(() => window.goalBudgetCall), { action: "resume", tokenBudget: 4800000, expectedTokenBudget: 4000000, expectedStartedAt: 123 });
  await desktop.screenshot({ path: `${out}/desktop.png`, animations: "disabled" });
  await desktop.close();
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  page.setDefaultTimeout(15000);
  await page.goto("http://127.0.0.1:5199/scripts/fixtures/mobile.html?longgoal=1&spent=1");
  await page.getByRole("navigation", { name: "主导航" }).getByRole("button", { name: "建造", exact: true }).click();
  await page.getByText("Loom 账号页重做", { exact: true }).click();
  await page.getByRole("navigation", { name: "建造支路" }).getByRole("button", { name: "运行", exact: true }).click();
  await page.locator(".goal-budget-editor").waitFor();
  assert.equal(await page.getByRole("button", { name: "继续目标", exact: true }).isEnabled(), false);
  assert.equal(await page.getByRole("button", { name: "保存预算并继续", exact: true }).isEnabled(), false);
  await page.locator(".goal-budget-editor input").fill("4500000");
  await page.getByRole("button", { name: "保存预算并继续", exact: true }).click();
  await page.locator(".goal-budget-balance").filter({ hasText: "总额 4,500,000" }).waitFor();
  await page.close();
  console.log("Goal budgets: exact total, explicit addition, save without resume, exhausted budget gating and 320/390/1280px layouts passed");
} finally { await browser.close(); }
