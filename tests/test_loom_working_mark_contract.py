import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = ROOT / "desktop-react" / "src" / "components"
LAB = ROOT / "desktop-react" / "scripts" / "fixtures" / "mark-lab"

# LoomWorkingMark: Loom's mark rebuilt from fitted geometry, with motion taken from its structure. Kept for later;
# the thinking row still draws ThinkingGlyph's bead (test_thinking_glyph_contract.py).


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def block(source: str, start: str, end: str) -> str:
    begin = source.index(start)
    return source[begin:source.index(end, begin)]


def keyframes(source: str, name: str) -> str:
    start = source.index(f"@keyframes {name} " + "{")
    depth = 0
    for index in range(source.index("{", start), len(source)):
        depth += {"{": 1, "}": -1}.get(source[index], 0)
        if depth == 0:
            return source[start:index + 1]
    raise AssertionError(f"unterminated @keyframes {name}")


def test_mark_is_drawn_from_the_geometry_fitted_to_the_original() -> None:
    mark = read(COMPONENTS / "LoomWorkingMark.tsx")
    geometry = read(COMPONENTS / "loomMarkGeometry.ts")

    assert 'import "./loom-working-mark.css";' in mark and 'from "./loomMarkGeometry";' in mark
    assert "<img" not in mark and 'aria-hidden="true"' in mark
    # The tool, the model and the original it was fitted to are kept together, so the geometry can be regenerated.
    assert "Generated by scripts/fixtures/mark-lab/mark_fit.py" in geometry
    assert all((LAB / name).exists() for name in ("mark_fit.py", "model.json", "loom-mark-512.png"))
    for name in ("SPHERE", "RIBBON_UPPER_BACK", "RIBBON_UPPER_FRONT", "RIBBON_LOWER", "EDGES_UPPER_BACK",
                 "EDGES_UPPER_FRONT", "EDGES_LOWER", "ARROW", "ARROW_DIRECTION", "ROUTE"):
        assert f"export const {name} = " in geometry, name
    # Gradients, the glow and the mask are per instance, so any number of marks can be on the page.
    assert "useId()" in mark and "id={`${id}lit`}" in mark
    # The original's layer order: the far side of the upper ribbon and the lower ribbon, the sphere, the ribbon where
    # it crosses in front of the sphere; the arrowhead on the motion layer above them.
    back = [mark.index(f"d={{{name}}} fill") for name in ("RIBBON_UPPER_BACK", "RIBBON_LOWER")]
    front = mark.index('d={RIBBON_UPPER_FRONT} className="lm-front"')
    assert back == sorted(back) and back[1] < mark.index('fill={url("sphere")}') < front
    assert mark.index('className="lm-base"') < mark.index('className="lm-motion"') < mark.index('d={ARROW} fill={url("arrow")}')
    # Light lies only on the ribbon and the arrowhead, never over the sphere where the ribbon passes behind it.
    lit = block(mark, "<mask id={`${id}lit`}", "</mask>")
    assert lit.index("RIBBON_LOWER") < lit.index('fill="#000"') < lit.index("RIBBON_UPPER_FRONT")
    # Its own classes: nothing of the thinking glyph's (tg-) is reused, so the two can never restyle each other.
    assert not re.search(r"\btg-|\.tg\b", mark + read(COMPONENTS / "loom-working-mark.css"))


def test_mark_motion_interpolates_and_keeps_its_base_still() -> None:
    css = read(COMPONENTS / "loom-working-mark.css")

    def props(name: str) -> set[str]:
        return set(re.findall(r"([a-z-]+)\s*:", re.sub(r"@keyframes[^{]+", "", keyframes(css, name))))

    assert props("lm-pulse") <= {"opacity", "transform"}
    assert props("lm-run") <= {"stroke-dashoffset", "animation-timing-function"}
    assert props("lm-arrow") <= {"transform"}
    assert props("lm-arrow-lit") <= {"opacity"}
    assert css.count("infinite") == 4
    # Chrome treats var() inside these keyframes as a discrete step: the run would jump, not travel.
    run, arrow = keyframes(css, "lm-run"), keyframes(css, "lm-arrow")
    assert "var(" not in run
    # The run reaches the arrowhead (100 along the route) as the arrowhead starts its push.
    assert "64% {\n    stroke-dashoffset: -70;" in run and "0%, 64%, 100% {\n    transform: translate(0, 0);" in arrow
    # The base and its glow filter never change; the moving parts are on their own layer so they never repaint it.
    assert ".lm-motion {\n  will-change: transform;" in css
    for name in ("lm-pulse", "lm-run", "lm-arrow", "lm-arrow-lit"):
        assert f"{name} var(--thinking-cycle, var(--loom-period-shimmer))" in css


def test_mark_holds_still_under_reduced_motion() -> None:
    css = read(COMPONENTS / "loom-working-mark.css")

    parts = (".lm-run", ".lm-arrow", ".lm-arrow-lit", ".lm-pulse")
    media = block(css, "@media (prefers-reduced-motion: reduce)", "\n}\n")
    assert all(part in media for part in parts) and "animation: none;" in media
    assert ".lm-light {\n    display: none;" in media
    setting = block(css, ':root[data-loom-reduced-motion="true"] .lm-run', "{")
    assert all(part in setting for part in parts[1:])
    assert ':root[data-loom-reduced-motion="true"] .lm-light {\n  display: none;' in css
