def test_glyph_is_the_loom_mark_built_from_its_own_geometry() -> None:
    glyph = read(COMPONENTS / "ThinkingGlyph.tsx")
    geometry = read(COMPONENTS / "loomMarkGeometry.ts")
    lab = ROOT / "desktop-react" / "scripts" / "fixtures" / "mark-lab"

    assert 'import "./thinking-glyph.css";' in glyph
    assert 'aria-hidden="true"' in glyph
    # Drawn from the geometry fitted to the original (the tool, the model and the original live together), not a
    # picture and not a hand-drawn approximation.
    assert 'from "./loomMarkGeometry";' in glyph and "<img" not in glyph
    assert "Generated by scripts/fixtures/mark-lab/mark_fit.py" in geometry
    for name in ("SPHERE", "RIBBON_UPPER_BACK", "RIBBON_UPPER_FRONT", "RIBBON_LOWER", "EDGES_UPPER_BACK",
                 "EDGES_UPPER_FRONT", "EDGES_LOWER", "ARROW", "ARROW_DIRECTION", "ROUTE"):
        assert f"export const {name} = " in geometry, name
    assert all((lab / name).exists() for name in ("mark_fit.py", "model.json", "loom-mark-512.png"))
    # Gradients, the glow and the mask are per instance, so any number of glyphs can be on the page.
    assert "useId()" in glyph and "id={`${id}lit`}" in glyph
    # The mark's layers in the original's order: the far side of the upper ribbon and the lower ribbon, the sphere,
    # the ribbon where it crosses in front of the sphere; the arrowhead on the motion layer above them.
    order = [glyph.index(f"d={{{name}}} fill") for name in ("RIBBON_UPPER_BACK", "RIBBON_LOWER")]
    front = glyph.index("d={RIBBON_UPPER_FRONT} className=\"tg-front\"")
    assert order == sorted(order) and order[1] < glyph.index("fill={url(\"sphere\")}") < front
    assert glyph.index('className="tg-base"') < glyph.index('className="tg-motion"') < glyph.index('d={ARROW} fill={url("arrow")}')
    # Light lies only on the ribbon and the arrowhead, never over the sphere where the ribbon passes behind it.
    lit = block(glyph, "<mask id={`${id}lit`}", "</mask>")
    assert lit.index("RIBBON_LOWER") < lit.index('fill="#000"') < lit.index("RIBBON_UPPER_FRONT")
    assert '<g className="tg-light" mask={url("lit")}>' in glyph

    for path in SRC.rglob("*.css"):
        if path.name in {"thinking-glyph.css", "inline-thinking.css", "workspace-panels.css"}:
            continue
        assert ".tg" not in read(path), path.name


def test_glyph_motion_interpolates_and_keeps_its_base_still() -> None:
    css = read(COMPONENTS / "thinking-glyph.css")

    def props(name: str) -> set[str]:
        return set(re.findall(r"([a-z-]+)\s*:", re.sub(r"@keyframes[^{]+", "", keyframes(css, name))))

    assert props("tg-pulse") <= {"opacity", "transform"}
    assert props("tg-run") <= {"stroke-dashoffset", "animation-timing-function"}
    assert props("tg-arrow") <= {"transform"}
    assert props("tg-arrow-lit") <= {"opacity"}
    # One run of light (three dashes of one animation), one push, one lit arrowhead, one pulse per cycle.
    assert css.count("infinite") == 4
    # Chrome treats var() inside these keyframes as a discrete step: the run would jump, not travel.
    run, arrow = keyframes(css, "tg-run"), keyframes(css, "tg-arrow")
    assert "var(" not in run
    # The run reaches the arrowhead (100 along the route) as the arrowhead starts its push.
    assert "64% {\n    stroke-dashoffset: -70;" in run and "0%, 64%, 100% {\n    transform: translate(0, 0);" in arrow
    # The base and its glow filter never change; the moving parts are on their own layer so they never repaint it.
    assert ".tg-motion {\n  will-change: transform;" in css


def test_label_is_lit_by_one_monochrome_band() -> None:
    row = read(COMPONENTS / "inline-thinking.css")

    shimmer = block(row, ".thinking-shimmer {\n  --shimmer-base", "\n}\n")
    # The label's own text painted through a gradient: no second copy of the
    # string (which had to be kept in sync by hand) and no overlay layer.
    assert "-webkit-background-clip: text;" in shimmer and "background-clip: text;" in shimmer
    assert "-webkit-text-fill-color: transparent;" in shimmer
    assert ".thinking-shimmer::after" not in row and "正在思考…\"" not in row.split(".thinking-shimmer {")[0]
    assert 'content: "正在' not in row
    # One hue: the gradient only mixes the label's own two tones (declared once,
    # above it), never a colour of its own.
    gradient = block(shimmer, "background-image: linear-gradient(", "\n  );")
    assert re.findall(r"#[0-9a-fA-F]{3,8}\b|rgba?\(", gradient) == []
    assert gradient.count("var(--shimmer-peak)") >= 5 and gradient.count("var(--shimmer-base)") >= 5
    # The band is feathered: it ramps up and down in several steps, not one edge.
    assert gradient.count("color-mix(in srgb") >= 6
    # Painted, not promoted: nothing here asks for a compositor layer behind text.
    assert "will-change" not in row
    assert "contain: paint;" in shimmer
    # The sweep itself only moves the background.
    sweep = keyframes(row, "thinking-text-shimmer")
    assert set(re.findall(r"([a-z-]+)\s*:", re.sub(r"@keyframes[^{]+", "", sweep))) == {"background-position"}
    # Forced colours drop backgrounds, so the plain label must come back.
    forced = block(row, "@media (forced-colors: active) {", "\n}\n")
    assert "-webkit-text-fill-color: currentColor;" in forced and "animation: none;" in forced


